"""Write the README's Projects section from GROUPS: each banner linked to its website, its repo chips under it."""

from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import escape

from visuals.projects import GROUPS, Group

START = "<!-- projects:start (generated by: uv run python -m visuals) -->"
END = "<!-- projects:end -->"

# Narrow banners below a 460px README column. GitHub's column narrows again at 768px and 1012px wide screens
# (the sidebar appears), hence two viewport ranges.
NARROW = "(max-width: 556px), (min-width: 768px) and (max-width: 844px)"
NARROW_DARK = (
    "(max-width: 556px) and (prefers-color-scheme: dark), "
    "(min-width: 768px) and (max-width: 844px) and (prefers-color-scheme: dark)"
)
DARK = "(prefers-color-scheme: dark)"


def banner(group: Group) -> str:
    name = f"assets/project-{group.key}"
    picture = (
        "<picture>\n"
        f'  <source media="{NARROW_DARK}" srcset="{name}-narrow-dark.svg">\n'
        f'  <source media="{NARROW}" srcset="{name}-narrow-light.svg">\n'
        f'  <source media="{DARK}" srcset="{name}-dark.svg">\n'
        f'  <img alt="{escape(f"{group.name}: {group.tagline}")}" src="{name}-light.svg" width="100%">\n'
        "</picture>"
    )
    return f'<a href="{group.url}">\n{picture}\n</a>' if group.url else picture


def chips(group: Group) -> str:
    # One per line: the line breaks are the wrap points when the row is wider than the column.
    lines = [
        f'<a href="{repo.url}"><picture><source media="{DARK}" srcset="assets/repo-{repo.key}-dark.svg">'
        f'<img alt="{repo.name}" src="assets/repo-{repo.key}-light.svg"></picture></a>'
        for repo in group.repos
    ]
    return "<p>\n" + "\n".join(lines) + "\n</p>"


def section() -> str:
    return "\n\n".join(f"{banner(g)}\n{chips(g)}" for g in GROUPS)


DOWNLOADS_START = "<!-- downloads:start (written weekly by: uv run python -m downloads) -->"
DOWNLOADS_END = "<!-- downloads:end -->"


def downloads_section(stats: list) -> str:
    """The downloads box (no link: its numbers are the content) and one chip per registry, in slot order, each
    linking to that registry's page. The alt texts carry the same numbers as the images, so the weekly run
    rewrites this block together with the SVGs."""
    from downloads.registries import PAGES
    from downloads.render import box_alt, chip_alt, in_slot_order

    name = "assets/downloads"
    box = (
        "<picture>\n"
        f'  <source media="{NARROW_DARK}" srcset="{name}-narrow-dark.svg">\n'
        f'  <source media="{NARROW}" srcset="{name}-narrow-light.svg">\n'
        f'  <source media="{DARK}" srcset="{name}-dark.svg">\n'
        f'  <img alt="{escape(box_alt(stats))}" src="{name}-light.svg" width="100%">\n'
        "</picture>"
    )
    lines = [
        f'<a href="{PAGES[s.key]}"><picture><source media="{DARK}" srcset="assets/registry-{s.key}-dark.svg">'
        f'<img alt="{escape(chip_alt(s))}" src="assets/registry-{s.key}-light.svg"></picture></a>'
        for s in in_slot_order(stats)
    ]
    return box + "\n<p>\n" + "\n".join(lines) + "\n</p>"


def _replace(text: str, start: str, end: str, body: str) -> str:
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n{body}\n{end}{tail}"


def update(readme: Path) -> None:
    """The Projects section; the downloads block belongs to the weekly run (update_downloads)."""
    text = readme.read_text(encoding="utf-8")
    readme.write_text(_replace(text, START, END, section()), encoding="utf-8")


def update_downloads(readme: Path, stats: list) -> bool:
    """Rewrite the downloads block from this week's numbers. False when the README has no such block."""
    text = readme.read_text(encoding="utf-8")
    if DOWNLOADS_START not in text:
        return False
    readme.write_text(_replace(text, DOWNLOADS_START, DOWNLOADS_END, downloads_section(stats)), encoding="utf-8")
    return True
