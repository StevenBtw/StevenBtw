"""Write the README's Projects section from GROUPS: each banner linked to its website, its repo chips under it."""

from __future__ import annotations

from pathlib import Path

from visuals.projects import GROUPS, Group

START = "<!-- projects:start (generated by: uv run python -m visuals) -->"
END = "<!-- projects:end -->"

# Narrow banners below a 460px README column. GitHub's column narrows again at 768px and 1012px wide screens
# (the sidebar appears), hence two viewport ranges.
NARROW = "(max-width: 556px), (min-width: 768px) and (max-width: 844px)"
NARROW_DARK = (
    "(max-width: 556px) and (prefers-color-scheme: dark), "
    "(min-width: 768px) and (max-width: 844px) and (prefers-color-scheme: dark)"
)
DARK = "(prefers-color-scheme: dark)"


def banner(group: Group) -> str:
    name = f"assets/project-{group.key}"
    picture = (
        "<picture>\n"
        f'  <source media="{NARROW_DARK}" srcset="{name}-narrow-dark.svg">\n'
        f'  <source media="{NARROW}" srcset="{name}-narrow-light.svg">\n'
        f'  <source media="{DARK}" srcset="{name}-dark.svg">\n'
        f'  <img alt="{group.name}: {group.tagline}" src="{name}-light.svg" width="100%">\n'
        "</picture>"
    )
    return f'<a href="{group.url}">\n{picture}\n</a>' if group.url else picture


def chips(group: Group) -> str:
    # One per line: the line breaks are the wrap points when the row is wider than the column.
    lines = [
        f'<a href="{repo.url}"><picture><source media="{DARK}" srcset="assets/repo-{repo.key}-dark.svg">'
        f'<img alt="{repo.name}" src="assets/repo-{repo.key}-light.svg"></picture></a>'
        for repo in group.repos
    ]
    return "<p>\n" + "\n".join(lines) + "\n</p>"


def section() -> str:
    return "\n\n".join(f"{banner(g)}\n{chips(g)}" for g in GROUPS)


def update(readme: Path) -> None:
    text = readme.read_text(encoding="utf-8")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    readme.write_text(f"{head}{START}\n{section()}\n{END}{tail}", encoding="utf-8")
